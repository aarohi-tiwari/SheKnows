import re

def extract_with_regex(text):
    """Extract years of experience and job titles using regex."""
    years = re.findall(r'(\d+)\s+years?', text.lower())
    roles = re.findall(r'\b(lead architect|junior dev|architect|developer|engineer)\b', text.lower())
    return {"years": list(set(years)), "roles": list(set(roles))}

regex_data = extract_with_regex(final_text)
print("🔍 Regex Extraction:", regex_data)

import spacy
nlp = spacy.load("en_core_web_sm")

def extract_with_spacy(text):
    """Use spaCy to extract skills and keywords."""
    doc = nlp(text)
    # Named entities like ORG, PRODUCT, LANGUAGE etc.
    skills = [ent.text for ent in doc.ents if ent.label_ in ["ORG", "PRODUCT", "LANGUAGE"]]
    # Extra keywords (nouns, proper nouns)
    keywords = [token.text for token in doc if token.pos_ in ["PROPN", "NOUN"] and not token.is_stop]
    return {"skills": list(set(skills)), "keywords": list(set(keywords))}

spacy_data = extract_with_spacy(final_text)
print(" spaCy Extraction:", spacy_data)

